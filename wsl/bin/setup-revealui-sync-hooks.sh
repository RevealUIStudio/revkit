#!/bin/bash
# setup-revealui-sync-hooks.sh — Set up git hooks in the WSL RevealUI repo
# to sync the Windows mirror on every commit, merge, checkout, and rewrite.
#
# RevealUI uses Husky (core.hooksPath = .husky/_), so user-facing hooks
# go in .husky/, NOT .git/hooks/. The actual sync script lives in
# .git/hooks/ (untracked, won't pollute the working tree).
#
# Configuration via env vars (paths baked into the generated hook):
#   REVEALUI_WSL_REPO     WSL-side authoritative repo
#                         (default: $HOME/suite/revealui, fallback: $HOME/projects/RevealUI)
#   REVEALUI_WIN_MIRROR   Windows-side mirror path
#                         (default: auto-discover under /mnt/e/projects/RevealUI,
#                          then any /mnt/c/Users/*/projects/RevealUI)
#
# Usage:
#   bash setup-revealui-sync-hooks.sh
#   REVEALUI_WSL_REPO=/custom/path bash setup-revealui-sync-hooks.sh
#   REVEALUI_WIN_MIRROR=/mnt/d/RevealUI bash setup-revealui-sync-hooks.sh

set -euo pipefail

# --- Discover WSL-side repo ---
if [ -n "${REVEALUI_WSL_REPO:-}" ]; then
    REPO="$REVEALUI_WSL_REPO"
elif [ -d "$HOME/suite/revealui/.git" ]; then
    REPO="$HOME/suite/revealui"
elif [ -d "$HOME/projects/RevealUI/.git" ]; then
    REPO="$HOME/projects/RevealUI"
else
    echo "ERROR: Could not find WSL RevealUI repo." >&2
    echo "  Looked at: \$HOME/suite/revealui, \$HOME/projects/RevealUI" >&2
    echo "  Set REVEALUI_WSL_REPO to override." >&2
    exit 1
fi

if [ ! -d "$REPO/.git" ]; then
    echo "ERROR: $REPO does not contain a .git directory." >&2
    exit 1
fi

# --- Discover Windows-side mirror (E: first, then any C: user) ---
if [ -n "${REVEALUI_WIN_MIRROR:-}" ]; then
    WINDOWS_MIRROR="$REVEALUI_WIN_MIRROR"
elif [ -d "/mnt/e/projects/RevealUI/.git" ]; then
    WINDOWS_MIRROR="/mnt/e/projects/RevealUI"
else
    WINDOWS_MIRROR=""
    for candidate in /mnt/c/Users/*/projects/RevealUI; do
        if [ -d "$candidate/.git" ]; then
            WINDOWS_MIRROR="$candidate"
            break
        fi
    done
fi

if [ -z "${WINDOWS_MIRROR:-}" ]; then
    echo "ERROR: Could not find Windows RevealUI mirror." >&2
    echo "  Looked at: /mnt/e/projects/RevealUI, /mnt/c/Users/*/projects/RevealUI" >&2
    echo "  Set REVEALUI_WIN_MIRROR to override." >&2
    exit 1
fi

GIT_HOOKS_DIR="$REPO/.git/hooks"
HUSKY_DIR="$REPO/.husky"
EXCLUDE_FILE="$REPO/.git/info/exclude"

echo "WSL repo:        $REPO"
echo "Windows mirror:  $WINDOWS_MIRROR"
echo ""

# 1. Create the sync script in .git/hooks/ (untracked).
#    Unquoted heredoc so $WINDOWS_MIRROR and $REPO bake in at setup time;
#    inner runtime variables ($WSL_REPO, $branch) are escaped.
cat > "$GIT_HOOKS_DIR/sync-windows-mirror" <<EOF
#!/bin/bash
# Sync Windows RevealUI mirror from local WSL repo.
# Runs in background so it never blocks the developer.
# Generated by setup-revealui-sync-hooks.sh — re-run that script to update paths.

WINDOWS_MIRROR="$WINDOWS_MIRROR"
WSL_REPO="$REPO"

# Only sync if Windows mirror exists
[ -d "\$WINDOWS_MIRROR/.git" ] || exit 0

(
  branch=\$(git -C "\$WSL_REPO" symbolic-ref --short HEAD 2>/dev/null) || branch="main"
  git -C "\$WINDOWS_MIRROR" fetch "\$WSL_REPO" "\$branch" 2>/dev/null
  git -C "\$WINDOWS_MIRROR" reset --hard FETCH_HEAD 2>/dev/null
) &
EOF
chmod +x "$GIT_HOOKS_DIR/sync-windows-mirror"
echo "Created $GIT_HOOKS_DIR/sync-windows-mirror"

# 2. Create Husky hooks in .husky/ (where Husky's dispatcher looks).
mkdir -p "$HUSKY_DIR"
for hook in post-commit post-merge post-checkout post-rewrite; do
    cat > "$HUSKY_DIR/$hook" <<'EOF'
#!/bin/bash
.git/hooks/sync-windows-mirror
EOF
    chmod +x "$HUSKY_DIR/$hook"
    echo "Created $HUSKY_DIR/$hook"
done

# 3. Add Husky hooks to .git/info/exclude so they don't pollute git status.
mkdir -p "$(dirname "$EXCLUDE_FILE")"
touch "$EXCLUDE_FILE"
for hook in post-commit post-merge post-checkout post-rewrite; do
    if ! grep -qF ".husky/$hook" "$EXCLUDE_FILE"; then
        echo ".husky/$hook" >> "$EXCLUDE_FILE"
        echo "Excluded .husky/$hook from git status"
    fi
done

# 4. Clean up old hooks from .git/hooks/ (dead code — Husky ignores them).
for hook in post-commit post-merge post-checkout post-rewrite; do
    if [ -f "$GIT_HOOKS_DIR/$hook" ] && grep -q "sync-windows-mirror" "$GIT_HOOKS_DIR/$hook" 2>/dev/null; then
        rm "$GIT_HOOKS_DIR/$hook"
        echo "Removed dead $GIT_HOOKS_DIR/$hook"
    fi
done

echo ""
echo "Verification:"
ls -la "$HUSKY_DIR"/{post-commit,post-merge,post-checkout,post-rewrite} 2>&1 || true
ls -la "$GIT_HOOKS_DIR/sync-windows-mirror" 2>&1
echo ""
echo "git status check:"
git -C "$REPO" status --short .husky/
